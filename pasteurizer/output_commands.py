"""Logical equipment commands, independent of hardware wiring."""

from dataclasses import dataclass
import math


@dataclass(frozen=True)
class OutputCommands:
    heater_3kw: bool = False
    heater_1kw: bool = False
    heating_circulation: bool = False

    transfer_pump_1: bool = False
    transfer_pump_2: bool = False
    manhole_drain: bool = False

    overflow_valve_1_open: bool = False
    overflow_valve_2_open: bool = False
    pasteurizer_isolation_open: bool = False
    control_valve_percent: float = 0.0

    biogas_compressor: bool = False

    # False allows the cabinet fan's local thermostat to operate.
    cabinet_fan_disabled: bool = False

    light_green: bool = False
    light_yellow: bool = False
    light_red: bool = False

    def __post_init__(self):
        for name, value in vars(self).items():
            if name == "control_valve_percent":
                continue

            if type(value) is not bool:
                raise ValueError(f"{name} must be True or False")

        position = self.control_valve_percent

        if (
            type(position) not in (int, float)
            or not math.isfinite(position)
            or not 0.0 <= position <= 100.0
        ):
            raise ValueError(
                "control_valve_percent must be between 0 and 100"
            )

INDICATOR_COMMANDS = ("light_green", "light_yellow", "light_red")

# Boolean equipment commands (everything except the analogue control valve
# and the indicators, which the arbiter generates itself).
SWITCHED_COMMANDS = (
    "heater_3kw",
    "heater_1kw",
    "heating_circulation",
    "transfer_pump_1",
    "transfer_pump_2",
    "manhole_drain",
    "overflow_valve_1_open",
    "overflow_valve_2_open",
    "pasteurizer_isolation_open",
    "biogas_compressor",
    "cabinet_fan_disabled",
)

CONTROL_VALVE_COMMAND = "control_valve_percent"

# Commands that need a permission before the arbiter passes them on.
PERMISSIONED_COMMANDS = SWITCHED_COMMANDS + (CONTROL_VALVE_COMMAND,)


@dataclass(frozen=True)
class OutputPermissions:
    """Which equipment may operate this cycle. Everything is denied by default.

    Generated by the process layer from mode, state, interlocks and alarms.
    reasons may explain denials, e.g. {"transfer_pump_1": "TRANSFER_1 trip"}.
    A permission allows a request; it never creates one.
    """

    heater_3kw: bool = False
    heater_1kw: bool = False
    heating_circulation: bool = False

    transfer_pump_1: bool = False
    transfer_pump_2: bool = False
    manhole_drain: bool = False

    overflow_valve_1_open: bool = False
    overflow_valve_2_open: bool = False
    pasteurizer_isolation_open: bool = False
    control_valve_percent: bool = False

    biogas_compressor: bool = False
    cabinet_fan_disabled: bool = False

    reasons: tuple[tuple[str, str], ...] = ()

    def __post_init__(self):
        for name in PERMISSIONED_COMMANDS:
            if type(getattr(self, name)) is not bool:
                raise ValueError(f"Permission {name} must be True or False")
        for name, _ in self.reasons:
            if name not in PERMISSIONED_COMMANDS:
                raise ValueError(f"Unknown permission {name!r} in reasons")

    @classmethod
    def only(cls, *names, reasons=None):
        """Permit exactly the named commands."""
        unknown = set(names) - set(PERMISSIONED_COMMANDS)
        if unknown:
            raise ValueError(f"Unknown permissions {sorted(unknown)}")
        return cls(
            **{name: True for name in names},
            reasons=tuple((reasons or {}).items()),
        )

    def reason(self, name: str) -> str | None:
        return dict(self.reasons).get(name)
